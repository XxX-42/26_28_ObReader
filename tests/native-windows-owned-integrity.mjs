import assert from 'node:assert/strict';
import {readFile,writeFile,readdir,stat} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import xxhash from 'xxhash-wasm';
import {readNativeSidecarTree} from './native-sidecar-isolation.mjs';
import {readNativeWalEvidence} from './native-wal-evidence.mjs';
const evidence='D:/Documents/Codes/2026_7_PdfWebReader/windows-native-014-evidence';
const vault='D:/Documents/Obsidian/测试插件';
const stage=process.argv[2];assert.match(stage,/^[a-z0-9-]+$/);
const sha=bytes=>createHash('sha256').update(bytes).digest('hex');
const existing=JSON.parse(await readFile(evidence+'/existing-data-before.json','utf8'));
for(const row of existing)assert.equal(sha(await readFile(row.path)),row.sha256,row.path);
const currentDefault=[];const walk=async dir=>{for(const e of await readdir(dir,{withFileTypes:true})){const p=dir+'/'+e.name;if(e.isDirectory())await walk(p);else currentDefault.push(p);}};
await walk(vault+'/00_Archive/20_PDFData');
// The frozen before-tree has only PDFData; VocabularyData was absent before init.
assert.ok(existing.every(r=>r.path.startsWith(vault+'/00_Archive/20_PDFData/')));
await assert.rejects(stat(vault+'/00_Archive/21_VocabularyData'),{code:'ENOENT'});
assert.deepEqual(currentDefault.sort(),existing.map(r=>r.path).sort(),'Default tree file membership changed');
const old=JSON.parse(await readFile(evidence+'/markdown-route-red.json','utf8'));
const canonical=old.hashes.filter(r=>r.path.includes('/VocabularyData/')&&!r.path.includes('/routing/markdown/'));
for(const row of canonical)assert.equal(sha(await readFile(row.path)),row.sha256,row.path);
const companion=JSON.parse(await readFile(evidence+'/queued-pluginreload-pass.json','utf8'));
const companionCanonical=companion.hashes.filter(r=>r.path.includes('/VocabularyData/')&&!r.path.includes('/routing/markdown/'));
for(const row of companionCanonical)assert.equal(sha(await readFile(row.path)),row.sha256,row.path);
const pdf=process.env.NATIVE_PDF_PATH||'PDF迁移测试/native-learning-loop-windows-014-20261023-1433/closed-pair/reader-renamed.pdf';
assert.ok(pdf.startsWith('PDF迁移测试/native-learning-loop-windows-014-20261023-1433/')&&!pdf.includes('..'));
const bytes=await readFile(vault+'/'+pdf);
assert.equal(sha(bytes),'3662ff519e485810520552bf301d8c3b2b917fd2f83303f4965d7abed367e113');
const {h64Raw}=await xxhash();const hash=b=>'xxh64-v1:'+h64Raw(b).toString(16).padStart(16,'0');
assert.equal(hash(bytes),'xxh64-v1:ffbe0d4d212547e5');
const baseline=JSON.parse(await readFile(evidence+'/two-ui-chains.json','utf8'));
const snapshot=baseline.runtime.snapshot;
const isolatedRoot=vault+'/.obsidian/plugins/pdf-web-reader/.native-learning-loop/windows-native-014-20261023-1433/PDFData';
const replay=await readNativeWalEvidence({files:await readNativeSidecarTree(isolatedRoot),isolatedRoot,virtualRoot:'00_Archive/20_PDFData',docKey:snapshot.docKey,documentId:snapshot.documentId,sourceHash:snapshot.source.sourceHash,viewerRevision:baseline.runtime.current,confirmedViewerRevision:baseline.runtime.confirmed,hash});
assert.deepEqual(replay.annotations.map(r=>r.uuid),['a2d1ef04-6750-4d3a-97a4-c67a0ed0b148']);
const report={stage,at:new Date().toISOString(),existingFiles:existing.length,existingMutationCount:0,defaultTreeMembershipUnchanged:true,canonicalFiles:canonical.length,canonicalMutationCount:0,companionCanonicalFiles:companionCanonical.length,companionMutationCount:0,sha256:sha(bytes),xxh64:hash(bytes),replay};
await writeFile(evidence+'/'+stage+'-integrity.json',JSON.stringify(report,null,2));
console.log(JSON.stringify({stage,existingFiles:existing.length,canonicalFiles:canonical.length,sourceSha256:sha(bytes),sourceXxh64:hash(bytes),uuids:replay.annotations.map(r=>r.uuid)}));
